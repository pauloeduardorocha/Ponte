const routes = Object.entries(HTTP_CACHE_ROUTES).map(([path, ttl]) => ({
  pattern: new RegExp('^' + path.replace(/\{[^}]+\}/g, '[^/]+') + '$'),
  ttl,
}));

export function responseCacheTtl(path: string): number {
  const url = new URL(path, 'https://cache.invalid');
  const pathname =
    url.pathname.replace(/^\/api\/v1(?=\/|$)/, '').replace(/\/$/, '') || '/';
  // Filtered catalogue membership depends on current inventory.
  if (pathname === '/library/books' && url.searchParams.has('available'))
    return 0;
  return routes.find((route) => route.pattern.test(pathname))?.ttl ?? 0;
}
